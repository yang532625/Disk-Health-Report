def t(key: str, lang: str = "es", **kwargs) -> str:
    lang = lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    text = STRINGS[lang].get(key, STRINGS[DEFAULT_LANG].get(key, key))
    if kwargs:
        return text.format(**kwargs)
    return text


def get_attr_name(attr_id: int, lang: str = "es") -> str:
    lang = lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    return ATTR_NAMES[lang].get(attr_id, f"Attribute {attr_id}")


def get_attr_meaning(attr_id: int, lang: str = "es") -> str:
    lang = lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    return ATTR_MEANINGS[lang].get(attr_id, "S.M.A.R.T. monitoring attribute." if lang == "en" else "Atributo de monitoreo S.M.A.R.T.")


def format_status(status: str, lang: str = "es") -> str:
    mapping = {
        "OK": "status_ok",
        "Nota": "status_note",
        "Alerta": "status_alert",
    }
    return t(mapping.get(status, "status_ok"), lang)


def format_date_long(lang: str = "es") -> str:
    now = datetime.now()
    months = MONTHS.get(lang, MONTHS["es"])
    if lang == "en":
        return f"{months[now.month - 1]} {now.day}, {now.year}"
    return f"{now.day} de {months[now.month - 1]} de {now.year}"


def format_datetime_short() -> str:
    return datetime.now().strftime("%d/%m/%Y %H:%M")
